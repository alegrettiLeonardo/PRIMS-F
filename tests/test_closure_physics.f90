program test_closure_physics
  use mod_kinds,only:wp
  use mod_void_helpers,only:ffan,Dffan,alpha2gamma,fvgamma
  use module_closure_law
  use,intrinsic::ieee_arithmetic,only:ieee_is_finite
  implicit none
  real(wp),parameter::pi=acos(-1.0_wp),diam=.0508_wp,area=pi*diam*diam/4.0_wp
  real(wp),parameter::rough=4.6e-5_wp,mu_l=.89e-3_wp,mu_g=1.85e-5_wp,sigma=.0728_wp,g=9.81_wp,tol=1e-12_wp
  real(wp)::x(5),q(5),v1,v2,v3,expected,cd,ud,cd2,ud2,d1,d2,h,fd,ga,wr,wu,theta,tau
  real(wp)::fractions(5)
  integer::st,k,count
  count=0
  v1=ffan(.001_wp,1000.0_wp,st)
  call check(st==0.and.abs(v1-.016_wp)<1e-15_wp,'Fanning laminar 16/Re')
  tau=fanning_wall_shear(1000.0_wp,.002_wp,.05_wp,.001_wp,0.0_wp,st)
  call close(tau,8.0_wp*.001_wp*.002_wp/.05_wp,1e-14_wp,'signed laminar shear')
  tau=fanning_wall_shear(1000.0_wp,-.002_wp,.05_wp,.001_wp,0.0_wp,st)
  call close(tau,-8.0_wp*.001_wp*.002_wp/.05_wp,1e-14_wp,'reverse laminar shear')
  tau=fanning_wall_shear(1000.0_wp,0.0_wp,.05_wp,.001_wp,0.0_wp,st)
  call check(st==0.and.tau==0.0_wp,'zero-speed shear has finite analytic limit')
  call Dffan(2150.0_wp,.001_wp,d1,d2,st)
  h=1e-7_wp
  fd=(ffan(.001_wp+h,2150.0_wp)-ffan(.001_wp-h,2150.0_wp))/(2*h)
  call close(d2,fd,1e-7_wp,'transition friction retains roughness derivative')
  v1=ffan(.001_wp,-1.0_wp,st)
  call check(st/=0.and..not.ieee_is_finite(v1),'negative Reynolds rejected')
  fractions=[1e-6_wp,.1_wp,.5_wp,.9_wp,1.0_wp-1e-6_wp]
  do k=1,size(fractions)
    ga=alpha2gamma(fractions(k),tol,st)
    call check(st==0.and.abs(fvgamma(fractions(k),ga))<2e-12_wp,'alpha-gamma round trip')
  enddo
  ga=alpha2gamma(-.1_wp,tol,st)
  call check(st/=0.and..not.ieee_is_finite(ga),'invalid alpha has explicit failure')
  x=[.3_wp,1000.0_wp,3.0_wp,.5_wp,2.0_wp]
  theta=-2.0_wp*pi/180.0_wp;wr=1000.0_wp;wu=.2_wp
  call evaluate(STRATIFIED,x,theta,wr,wu,g,v1,st)
  call check(st==0,'stratified state admissible')
  call evaluate(STRATIFIED,x,theta,wr,wu,0.0_wp,v2,st)
  expected=-(x(2)-x(3))*g*diam*sin(theta)/(4*wr*wu**2)
  call close(v1-v2,expected,1e-11_wp,'Burr Eq8 gravity magnitude and sign')
  call evaluate(STRATIFIED,x,theta,1.0_wp,1.0_wp,g,v2,st)
  call close(v1*wr*wu**2,v2,2e-11_wp,'stratified physical residual scale invariance')
  q=x;q(4:5)=0.0_wp
  call evaluate(STRATIFIED,q,theta,wr,wu,g,v3,st)
  call check(st==0,'zero phase speeds avoid singular friction')
  call close(v3,expected,1e-11_wp,'static stratified residual is gravity only')
  q=x;q(4)=-.5_wp
  call evaluate(STRATIFIED,q,theta,wr,wu,0.0_wp,v1,st)
  q(4:5)=-q(4:5)
  call evaluate(STRATIFIED,q,theta,wr,wu,0.0_wp,v2,st)
  call close(v1,-v2,1e-12_wp,'countercurrent signed shear reversal')
  call derivative_check(STRATIFIED,x,theta,wr,wu)
  call stratified_threshold_checks()
  x=[.3_wp,1000.0_wp,3.0_wp,.2_wp,.4_wp];theta=.6_wp
  call coeff(x,theta,wr,wu,BENDIKSEN,cd,ud,st)
  call close(cd,1.05_wp+.15_wp*sin(theta),1e-14_wp,'Balino low-Froude Cd uses sin(theta)')
  call close(ud,sqrt(g*diam)*(.35_wp*sin(theta)+.54_wp*cos(theta)),1e-14_wp,'Balino low-Froude drift')
  call coeff(x,theta,1.0_wp,.4_wp,BENDIKSEN,cd2,ud2,st)
  call close(cd,cd2,1e-14_wp,'Cd scale invariance')
  call close(ud,ud2,1e-14_wp,'dimensional Ud scale invariance')
  call evaluate(BENDIKSEN,x,theta,wr,wu,g,v1,st)
  call evaluate(BENDIKSEN,x,theta,1.0_wp,.4_wp,g,v2,st)
  call close(v1*wu,v2*.4_wp,1e-13_wp,'drift residual scale invariance')
  call derivative_check(BENDIKSEN,x,theta,wr,wu)
  call coeff(x,theta,wr,wu,MONTGOMERY,cd,ud,st)
  call close(cd,1.05_wp+.15_wp*sin(theta)**2,1e-14_wp,'Montgomery is a distinct selectable model')
  x(4:5)=5.0_wp
  call coeff(x,theta,wr,wu,BENDIKSEN,cd,ud,st)
  call close(cd,1.2_wp,1e-14_wp,'Balino high-Froude Cd')
  call close(ud,.35_wp*sqrt(g*diam)*sin(theta),1e-14_wp,'Balino high-Froude drift changes branch')
  call derivative_check(BENDIKSEN,x,theta,wr,wu)
  x(4)=-.2_wp;x(5)=.4_wp
  call evaluate(BENDIKSEN,x,theta,wr,wu,g,v1,st)
  call check(st==0.and.ieee_is_finite(v1),'signed countercurrent drift evaluates without clipping')
  call derivative_check(BENDIKSEN,x,theta,wr,wu)
  call evaluate(BHAGWAT,x,theta,wr,wu,g,v1,st)
  call check(st==CLOSURE_DOMAIN.and..not.ieee_is_finite(v1),'Bhagwat countercurrent state explicitly outside qualified domain')
  call bhagwat_checks()
  call evaluate(BENDIKSEN,x,pi,wr,wu,g,v1,st)
  call check(st==CLOSURE_DOMAIN.and..not.ieee_is_finite(v1),'unsupported inclination explicit')
  write(*,'(a,i0,a)')'PASS closure physics: ',count,' assertions'
contains
  subroutine bhagwat_checks()
    !! Expected values are independent 80-digit evaluations of the printed
    !! Eq.116--128, generated by scripts/generate_bhagwat_fixtures.py.
    real(wp)::cases(10,7),cd_ref(7),ud_ref(7),xx(5),nd(5),cc,uu,ff,ff2,dc(5),du(5)
    real(wp)::rscale,uscale,dd,aa,mu,th,eps,sig,a0,b0,mid,jl,jg,fleft,fmid
    integer::i,j,code
    cases(:,1)=[.3_wp,1000.0_wp,3.0_wp,.5_wp,2.0_wp,.6_wp,diam,rough,mu_l,sigma]
    cases(:,2)=[.7_wp,998.0_wp,20.0_wp,.1_wp,.8_wp,pi/2,diam,rough,mu_l,sigma]
    cases(:,3)=[.1_wp,850.0_wp,5.0_wp,.02_wp,.2_wp,0.0_wp,.5_wp,rough,.02_wp,.03_wp]
    cases(:,4)=[.8_wp,1000.0_wp,3.0_wp,.2_wp,3.0_wp,-.3_wp,diam,rough,mu_l,sigma]
    cases(:,5)=[.2_wp,1000.0_wp,3.0_wp,.1_wp,.1_wp,-.3_wp,diam,rough,mu_l,sigma]
    cases(:,6)=[.95_wp,1000.0_wp,3.0_wp,0.0_wp,.1_wp,pi/2,diam,rough,mu_l,sigma]
    cases(:,7)=[.05_wp,1000.0_wp,3.0_wp,.3_wp,0.0_wp,.2_wp,diam,rough,mu_l,sigma]
    cd_ref=[1.112784729625017850_wp,1.107233633344603233_wp,1.630120466180383036_wp, &
      1.121339596598625349_wp,1.122357662447589342_wp,1.032890976833016809_wp,1.083834171241248437_wp]
    ud_ref=[.3355791638136027018_wp,.1339674183537203252_wp,.1468931383426924119_wp, &
      .1029132630277126063_wp,-.2058265260554252126_wp,.05516542717590429391_wp,.3507729724944279147_wp]
    do i=1,7
      xx=cases(1:5,i);th=cases(6,i);dd=cases(7,i);eps=cases(8,i);mu=cases(9,i);sig=cases(10,i)
      aa=pi*dd*dd/4
      do j=1,3
        if(j==1)then
          rscale=1.0_wp;uscale=1.0_wp
        else if(j==2)then
          rscale=1000.0_wp;uscale=.2_wp
        else
          rscale=4.3_wp;uscale=7.35_wp
        endif
        nd=[xx(1),xx(2)/rscale,xx(3)/rscale,xx(4)/uscale,xx(5)/uscale]
        call CdUd_drift(nd(1),nd(2),nd(3),nd(4),nd(5),th,dd,aa,eps,g,mu,mu_g,sig, &
          uscale,rscale,tol,cc,uu,BHAGWAT,code)
        call check(code==0,'Bhagwat 2015 coefficient fixture status')
        call close(cc,cd_ref(i),3e-13_wp,'Bhagwat Eq116 independent high-precision Cd and scale invariance')
        call close(uu,ud_ref(i),3e-13_wp,'Bhagwat Eq122 independent high-precision Ud and scale invariance')
        call lei_fechamento_or_ndim_simp(nd(1),nd(2),nd(3),nd(4),nd(5),th,dd,aa,eps,g,mu,mu_g,sig, &
          uscale,rscale,tol,ff,BHAGWAT,code)
        call check(code==0,'Bhagwat residual fixture status')
        ff2=xx(1)*(-xx(5)+cd_ref(i)*((1-xx(1))*xx(4)+xx(1)*xx(5))+ud_ref(i))
        call close(ff*uscale,ff2,3e-13_wp,'Bhagwat same physical residual for all scales')
        call DCdUd_swananda(nd(1),nd(2),nd(3),nd(4),nd(5),th,dd,aa,eps,g,mu,mu_g,sig,uscale,rscale,tol, &
          dc(1),dc(2),dc(3),dc(4),dc(5),du(1),du(2),du(3),du(4),du(5),code)
        call check(code==0.and.all(ieee_is_finite(dc)).and.all(ieee_is_finite(du)), &
          'Bhagwat coefficient derivatives finite including zero phase speed')
        if(i<=5)call bhagwat_derivative_check(nd,th,dd,eps,mu,sig,rscale,uscale)
      enddo
    enddo
    xx=cases(1:5,1);xx(4:5)=0.0_wp
    call evaluate(BHAGWAT,xx,.6_wp,1.0_wp,1.0_wp,g,ff,code)
    call check(code/=0.and..not.ieee_is_finite(ff),'Bhagwat zero total flux is not silently extrapolated')
    xx=cases(1:5,1);xx(3)=xx(2)
    call evaluate(BHAGWAT,xx,.6_wp,1.0_wp,1.0_wp,g,ff,code)
    call check(code/=0.and..not.ieee_is_finite(ff),'Bhagwat nonpositive density difference rejected')
    xx=cases(1:5,1)
    call evaluate(BHAGWAT,xx,-51*pi/180,1.0_wp,1.0_wp,g,ff,code)
    call check(code==CLOSURE_DOMAIN.and..not.ieee_is_finite(ff),'Bhagwat angular domain explicit')
    call evaluate(99,xx,.6_wp,1.0_wp,1.0_wp,g,ff,code)
    call check(code==CLOSURE_UNSUPPORTED.and..not.ieee_is_finite(ff),'unknown closure ID remains unsupported')
    xx=cases(1:5,1)
    xx(5)=.1_wp*sqrt(g*diam*cos(-.3_wp))*sqrt((xx(2)-xx(3))/xx(3))/xx(1)
    call evaluate(BHAGWAT,xx,-.3_wp,1.0_wp,1.0_wp,g,ff,code)
    call check(code==0.and.ieee_is_finite(ff),'Bhagwat primal selects stated C4 threshold branch')
    call Dlei_fechamento_or_ndim_simp(xx(1),xx(2),xx(3),xx(4),xx(5),-.3_wp,diam,area,rough,g,mu_l,mu_g,sigma, &
      1.0_wp,1.0_wp,tol,dc(1),dc(3),dc(2),dc(5),dc(4),BHAGWAT,code)
    call check(code==CLOSURE_DERIVATIVE.and..not.any(ieee_is_finite(dc)), &
      'Bhagwat C4 jump reports undefined derivative without successful NaN')
    ! The independently selected superficial fluxes close through an alpha root.
    jl=.2_wp;jg=.5_wp;a0=1e-9_wp;b0=1.0_wp-1e-9_wp
    xx=[a0,1000.0_wp,3.0_wp,jl/(1-a0),jg/a0]
    call evaluate(BHAGWAT,xx,.6_wp,1.0_wp,1.0_wp,g,fleft,code)
    call check(code==0,'Bhagwat alpha bracket left domain')
    do i=1,60
      mid=.5_wp*(a0+b0);xx=[mid,1000.0_wp,3.0_wp,jl/(1-mid),jg/mid]
      call evaluate(BHAGWAT,xx,.6_wp,1.0_wp,1.0_wp,g,fmid,code)
      call check(code==0,'Bhagwat alpha root sample domain')
      if(fmid*fleft<=0.0_wp)then
        b0=mid
      else
        a0=mid;fleft=fmid
      endif
    enddo
    call check(abs(fmid)<2e-13_wp,'Bhagwat recovered alpha closes same drift residual')
    call derivative_check(BHAGWAT,xx,.6_wp,1000.0_wp,.2_wp)
  end subroutine
  subroutine bhagwat_derivative_check(nd,th,dd,eps,mu,sig,rscale,uscale)
    real(wp),intent(in)::nd(5),th,dd,eps,mu,sig,rscale,uscale
    real(wp)::dc(5),du(5),der(5),pp(5),mm(5),cp,cm,up,um,fp,fm,hh,aa
    integer::j,code
    aa=pi*dd*dd/4
    call DCdUd_swananda(nd(1),nd(2),nd(3),nd(4),nd(5),th,dd,aa,eps,g,mu,mu_g,sig,uscale,rscale,tol, &
      dc(1),dc(2),dc(3),dc(4),dc(5),du(1),du(2),du(3),du(4),du(5),code)
    call check(code==0,'Bhagwat analytic coefficient derivative status')
    call Dlei_fechamento_or_ndim_simp(nd(1),nd(2),nd(3),nd(4),nd(5),th,dd,aa,eps,g,mu,mu_g,sig, &
      uscale,rscale,tol,der(1),der(3),der(2),der(5),der(4),BHAGWAT,code)
    call check(code==0,'Bhagwat analytic residual derivative status')
    do j=1,5
      hh=1e-5_wp*max(abs(nd(j)),1e-3_wp)
      pp=nd;mm=nd;pp(j)=pp(j)+hh;mm(j)=mm(j)-hh
      call CdUd_drift(pp(1),pp(2),pp(3),pp(4),pp(5),th,dd,aa,eps,g,mu,mu_g,sig, &
        uscale,rscale,tol,cp,up,BHAGWAT,code)
      call check(code==0,'Bhagwat coefficient FD plus domain')
      call CdUd_drift(mm(1),mm(2),mm(3),mm(4),mm(5),th,dd,aa,eps,g,mu,mu_g,sig, &
        uscale,rscale,tol,cm,um,BHAGWAT,code)
      call check(code==0,'Bhagwat coefficient FD minus domain')
      call close(dc(j),(cp-cm)/(2*hh),2e-7_wp,'Bhagwat analytic Cd derivative versus independent FD')
      call close(du(j),(up-um)/(2*hh),2e-7_wp,'Bhagwat analytic SI Ud derivative versus independent FD')
      call lei_fechamento_or_ndim_simp(pp(1),pp(2),pp(3),pp(4),pp(5),th,dd,aa,eps,g,mu,mu_g,sig, &
        uscale,rscale,tol,fp,BHAGWAT,code)
      call check(code==0,'Bhagwat residual FD plus domain')
      call lei_fechamento_or_ndim_simp(mm(1),mm(2),mm(3),mm(4),mm(5),th,dd,aa,eps,g,mu,mu_g,sig, &
        uscale,rscale,tol,fm,BHAGWAT,code)
      call check(code==0,'Bhagwat residual FD minus domain')
      call close(der(j),(fp-fm)/(2*hh),2e-7_wp,'Bhagwat derivative is of the same residual')
    enddo
  end subroutine
  subroutine check(condition,label)
    logical,intent(in)::condition
    character(*),intent(in)::label
    if(.not.condition)then
      write(*,'(a)')'FAIL: '//label
      error stop 1
    endif
    count=count+1
  end subroutine
  subroutine close(a,b,eps,label)
    real(wp),intent(in)::a,b,eps
    character(*),intent(in)::label
    if(.not.all(ieee_is_finite([a,b])))then
      write(*,*)label,a,b
      call check(.false.,label)
    endif
    if(abs(a-b)>eps*max(1.0_wp,abs(a),abs(b)))write(*,*)label,a,b,abs(a-b)
    call check(abs(a-b)<=eps*max(1.0_wp,abs(a),abs(b)),label)
  end subroutine
  subroutine evaluate(model,xx,th,rscale,uscale,gravity,val,istat)
    integer,intent(in)::model
    real(wp),intent(in)::xx(5),th,rscale,uscale,gravity
    real(wp),intent(out)::val
    integer,intent(out)::istat
    call lei_fechamento_or_ndim_simp(xx(1),xx(2)/rscale,xx(3)/rscale,xx(4)/uscale,xx(5)/uscale, &
      th,diam,area,rough,gravity,mu_l,mu_g,sigma,uscale,rscale,tol,val,model,istat)
  end subroutine
  subroutine coeff(xx,th,rscale,uscale,model,c,vd,istat)
    real(wp),intent(in)::xx(5),th,rscale,uscale
    integer,intent(in)::model
    real(wp),intent(out)::c,vd
    integer,intent(out)::istat
    call CdUd_drift(xx(1),xx(2)/rscale,xx(3)/rscale,xx(4)/uscale,xx(5)/uscale, &
      th,diam,area,rough,g,mu_l,mu_g,sigma,uscale,rscale,tol,c,vd,model,istat)
  end subroutine
  subroutine derivative_check(model,xx,th,rscale,uscale)
    integer,intent(in)::model
    real(wp),intent(in)::xx(5),th,rscale,uscale
    real(wp)::nd(5),der(5),plus(5),minus(5),hh,fp,fm,numeric
    integer::j,istat
    nd=[xx(1),xx(2)/rscale,xx(3)/rscale,xx(4)/uscale,xx(5)/uscale]
    call Dlei_fechamento_or_ndim_simp(nd(1),nd(2),nd(3),nd(4),nd(5),th,diam,area,rough,g,mu_l,mu_g,sigma, &
      uscale,rscale,tol,der(1),der(3),der(2),der(5),der(4),model,istat)
    call check(istat==0,'closure derivative status')
    do j=1,5
      hh=1e-5_wp*max(abs(nd(j)),1e-3_wp)
      plus=nd;minus=nd;plus(j)=plus(j)+hh;minus(j)=minus(j)-hh
      call lei_fechamento_or_ndim_simp(plus(1),plus(2),plus(3),plus(4),plus(5),th,diam,area,rough,g,mu_l,mu_g, &
        sigma,uscale,rscale,tol,fp,model,istat)
      call check(istat==0,'plus difference status')
      call lei_fechamento_or_ndim_simp(minus(1),minus(2),minus(3),minus(4),minus(5),th,diam,area,rough,g,mu_l,mu_g, &
        sigma,uscale,rscale,tol,fm,model,istat)
      call check(istat==0,'minus difference status')
      numeric=(fp-fm)/(2*hh)
      call close(der(j),numeric,2e-5_wp,'derivative of same closure function')
    enddo
  end subroutine
  subroutine stratified_threshold_checks()
    real(wp)::xx(5),gg,dl,dg,th,targets_g(4),targets_l(6)
    integer::i,code
    targets_g=[1999.9874026_wp,2000.0269066_wp,2299.99_wp,2300.01_wp]
    targets_l=[1999.99_wp,2000.01_wp,2199.99_wp,2200.01_wp,2299.99_wp,2300.01_wp]
    xx=[.3_wp,1000.0_wp,3.0_wp,0.0_wp,0.0_wp]
    th=-2.0_wp*pi/180.0_wp
    gg=alpha2gamma(xx(1),1e-13_wp,code)
    dl=(1-xx(1))*diam/gg
    dg=xx(1)*diam/(1-gg+sin(pi*gg)/pi)
    xx(4)=43036.0_wp*mu_l/(xx(2)*dl)
    do i=1,size(targets_g)
      xx(5)=targets_g(i)*mu_g/(xx(3)*dg)
      call one_sided_derivative_check(xx,th)
    enddo
    xx(5)=10000.0_wp*mu_g/(xx(3)*dg)
    do i=1,size(targets_l)
      xx(4)=targets_l(i)*mu_l/(xx(2)*dl)
      call one_sided_derivative_check(xx,th)
    enddo
    xx(4)=-43036.0_wp*mu_l/(xx(2)*dl)
    xx(5)=2000.0269066_wp*mu_g/(xx(3)*dg)
    call one_sided_derivative_check(xx,th)
    xx(4:5)=0.0_wp
    call one_sided_derivative_check(xx,th)
  end subroutine
  function branch_signature(xx) result(branches)
    real(wp),intent(in)::xx(5)
    integer::branches(3),code
    real(wp)::gg,dl,dg,rel,reg
    gg=alpha2gamma(xx(1),1e-13_wp,code)
    dl=(1-xx(1))*diam/gg
    dg=xx(1)*diam/(1-gg+sin(pi*gg)/pi)
    rel=xx(2)*abs(xx(4))*dl/mu_l
    reg=xx(3)*abs(xx(5))*dg/mu_g
    branches=[merge(1,merge(2,3,rel<=2300.0_wp),rel<2000.0_wp), &
      merge(1,merge(2,3,reg<=2300.0_wp),reg<2000.0_wp), &
      merge(1,merge(2,3,rel<2200.0_wp),rel<=2000.0_wp)]
  end function
  subroutine one_sided_derivative_check(xx,th)
    !! Independent second-order differences, restricted to the same Reynolds
    !! branches. A central secant crossing a kink is not a derivative oracle.
    real(wp),intent(in)::xx(5),th
    real(wp)::der(5),x1(5),x2(5),hh,direction,f0,f1,f2,numeric,scale
    integer::j,k,code,base(3),sgn
    logical::inside
    call Dlei_fechamento_or_ndim_simp(xx(1),xx(2),xx(3),xx(4),xx(5),th,diam,area,rough,g,mu_l,mu_g,sigma, &
      1.0_wp,1.0_wp,tol,der(1),der(3),der(2),der(5),der(4),STRATIFIED,code)
    call check(code==0,'analytic stratified derivative near branch threshold')
    call evaluate(STRATIFIED,xx,th,1.0_wp,1.0_wp,g,f0,code)
    base=branch_signature(xx)
    do j=1,5
      hh=1e-7_wp*max(abs(xx(j)),1.0_wp)
      inside=.false.
      do k=1,20
        do sgn=1,-1,-2
          direction=real(sgn,wp)
          x1=xx;x2=xx;x1(j)=x1(j)+direction*hh;x2(j)=x2(j)+direction*2*hh
          inside=all(branch_signature(x1)==base).and.all(branch_signature(x2)==base)
          if(inside)exit
        enddo
        if(inside)exit
        hh=0.5_wp*hh
      enddo
      call check(inside,'finite-difference samples stay on constitutive branch')
      call evaluate(STRATIFIED,x1,th,1.0_wp,1.0_wp,g,f1,code)
      call check(code==0,'first one-sided closure sample admissible')
      call evaluate(STRATIFIED,x2,th,1.0_wp,1.0_wp,g,f2,code)
      call check(code==0,'second one-sided closure sample admissible')
      numeric=direction*(-3*f0+4*f1-f2)/(2*hh)
      scale=max(abs(der(j)),abs(numeric),1e-6_wp)
      if(abs(der(j)-numeric)>1e-4_wp*scale)write(*,*)'Branch derivative mismatch',base,j,der(j),numeric
      call check(abs(der(j)-numeric)<=1e-4_wp*scale,'local analytic derivative equals one-sided same-branch difference')
    enddo
  end subroutine
end program test_closure_physics
